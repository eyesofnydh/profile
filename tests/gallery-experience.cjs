const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE);
(async()=>{const b=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_PATH});
const p=await b.newPage({viewport:{width:1440,height:1100},hasTouch:true});
  await p.emulateMedia({reducedMotion:'reduce'});
  await p.goto('http://localhost:4173');
  await p.locator('[data-layout="grid"]').click();
  await p.locator('.photo-card').first().waitFor();
  await p.locator('#gallery').evaluate(e=>e.scrollIntoView());
  await p.evaluate(()=>Promise.all([...document.querySelectorAll('.photo-view img')].slice(0,5).map(i=>i.decode())));
  await p.screenshot({path:'tests/gallery-mosaic.png'});
  await p.locator('.photo-view').first().click();
  await p.locator('#dialog-image').evaluate(i=>i.decode());
  await p.screenshot({path:'tests/gallery-viewer.png'});
  await p.setViewportSize({width:390,height:844});
  await p.locator('#dialog-image').evaluate(i=>{const r=i.getBoundingClientRect();
const make=x=>new Touch({identifier:1,target:i,clientX:x,clientY:r.top+r.height/2});i.dispatchEvent(new TouchEvent('touchstart',{touches:[make(r.right-20)],bubbles:true}));i.dispatchEvent(new TouchEvent('touchend',{changedTouches:[make(r.left+20)],bubbles:true}));});
  assert.equal(await p.locator('#photo-caption').innerText(),'Together by the ocean');
  await p.locator('#dialog-image').evaluate(i=>i.decode());
  assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await p.screenshot({path:'tests/gallery-viewer-mobile.png'});
  await p.keyboard.press('Escape');
  await p.setViewportSize({width:1440,height:1000});
  await p.emulateMedia({reducedMotion:'no-preference'});
  await p.waitForFunction(()=>document.querySelector('#motion-toggle').textContent==='Pause motion');
  await p.evaluate(()=>window.scrollTo({top:350,behavior:'instant'}));
  await p.waitForFunction(()=>document.querySelector('.hero-frame').style.translate.split(' ').some(n=>parseFloat(n)!==0));
  assert.equal(await p.locator('.hero-frame').evaluate(e=>e.style.translate.split(' ').some(n=>parseFloat(n)!==0)),true);
  await p.locator('#motion-toggle').click();
  await p.waitForFunction(()=>document.querySelector('.hero-frame').style.translate.split(' ').every(n=>parseFloat(n)===0));
  assert.equal(await p.locator('.hero-frame').evaluate(e=>e.style.translate.split(' ').every(n=>parseFloat(n)===0)),true);
  await b.close();console.log('PASS: mobile swipe navigation, viewer sizing, scroll depth, and motion-pause reset.');})();
